describe("radical (Snowball português)", () => {
  test.each(DOMINIO)("%s → %s", (palavra, esperado) => {
    expect(radical(palavra)).toBe(esperado);
  });
  test("amostra do vocabulário da base", () => {
    for (const [palavra, esperado] of AMOSTRA) expect([palavra, radical(palavra)]).toEqual([palavra, esperado]);
  });
});
